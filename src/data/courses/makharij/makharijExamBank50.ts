/**
 * دالة مساعدة لاختيار 35 سؤالاً عشوائياً من بنك الأسئلة الـ 50
 * مع خلط الخيارات لكل سؤال لتحقيق التقييم التفاعلي الدقيق
 */
export function getRandomMakharijExamQuestions(count: number = 35): ComprehensiveExamQuestion[] {
  const bankCopy = [...MAKHARIJ_EXAM_BANK_50];
  
  // خلط فيشر-ياتس (Fisher-Yates) العشوائي
  for (let i = bankCopy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [bankCopy[i], bankCopy[j]] = [bankCopy[j], bankCopy[i]];
  }
  
  // اختيار العدد المطلوب (35 سؤالاً)
  return bankCopy.slice(0, Math.min(count, bankCopy.length));
}
